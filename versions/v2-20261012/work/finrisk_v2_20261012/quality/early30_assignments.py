def export():
    dest=OUT/'early30_overlays.jsonl'
    records=[json.loads(s) for s in dest.read_text(encoding='utf-8').splitlines() if s.strip()] if dest.exists() else []
    existing={x['file_id']:x for x in records}
    for fid,groups in SPECS.items():
        if fid in existing:
            assert existing[fid]['base_draft_json_sha256']==get(fid)[2]['draft_json_sha256']
            continue
        draft,text,*_=get(fid)
        tags=[]
        for b,group in zip(draft['behaviors'],groups):
            quotes=list(dict.fromkeys([b['finding_quote']]+b.get('observed_scene',{}).get('quotes',[])+EXTRA_QUOTES.get((fid,b['local_key']),[])))
            unknown=b['actor_role']=='unknown'
            tags.append([tag(name,quotes,('仅同文书关联：' if unknown else '')+reason,conditions=['进一步确认本标签机制所需的具体动作、对象和责任范围；未载事项保持未知。'],basis='inferred' if unknown else basis,confidence='medium' if unknown and confidence=='high' else confidence,scope='document_related' if unknown else 'behavior_context',limitations=[limit]+(['actor_role=unknown，行为、责任或列项归属没有明确对应。'] if unknown else [])+['检索候选，不认定未载行为或个人责任。']) for name,basis,confidence,reason,limit in group])
        records.append(build_overlay(fid,tags,limitations=['历史source_issues与unresolved原值保留；其中旧零标签判断仅为历史待核记录，当前标签以本overlay为候选。']))
        if len(records)%5==0:
            checkpoint=OUT/'early30_overlays.jsonl.tmp'
            write_jsonl(checkpoint,records)
            checkpoint.replace(dest)
    temp=OUT/'early30_overlays.jsonl.tmp'
    write_jsonl(temp,records)
    temp.replace(dest)
    print(json.dumps({'documents':len(records),'behaviors':sum(len(x['updated_draft']['behaviors']) for x in records),'path':str(OUT/'early30_overlays.jsonl')},ensure_ascii=False))

