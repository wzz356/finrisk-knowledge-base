def main():
    items = [json.loads(line) for line in INPUT.read_text(encoding="utf-8").splitlines() if line.strip()]
    assert len(items) == len(OPINIONS) == 42
    assert len({item["item_id"] for item in items}) == 42
    rows = []
    for item, (helpful, relation, quote, reason, warnings) in zip(items, OPINIONS):
        assert type(helpful) is bool
        assert relation in {"direct", "partial", "irrelevant"}
        assert type(reason) is str and reason
        assert all(type(warning) is str for warning in warnings)
        if helpful:
            assert quote, item["item_id"]
            assert quote in item["displayed_text"], item["item_id"]
            assert any(quote in segment["text"] for segment in item["source_segments"]), item["item_id"]
            assert relation in {"direct", "partial"}
        else:
            assert relation == "irrelevant"
        canonical = json.dumps(item, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)
        rows.append({
            "item_id": item["item_id"],
            "item_sha256": hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
            "helpful": helpful,
            "relation": relation,
            "quote": quote,
            "reason": reason,
            "warnings": warnings,
            "origin": "current_session_model",
            "human_approved": False,
        })
    # 拒绝覆盖已有输出。所有逐字引文在开写前完成验证。
    with OUTPUT.open("x", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, allow_nan=False) + "\n")
    print(json.dumps({
        "rows_read": len(items),
        "rows_written": len(rows),
        "pending": 0,
        "helpful": sum(row["helpful"] for row in rows),
        "not_helpful": sum(not row["helpful"] for row in rows),
        "all_positive_quotes_inside_one_original_segment": True,
        "output": str(OUTPUT),
    }, ensure_ascii=False))


if __name__ == "__main__":
    main()
