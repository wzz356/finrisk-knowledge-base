def main():
    packets = {row["query_id"]: row for row in demo.rows(demo.OUT / "evidence_packets.jsonl")}
    if set(packets) != set(SPECS):
        raise ValueError("Session decisions must cover exactly this packet population")
    judgments = []
    for qid, spec in SPECS.items():
        decision, reason, risk_labels, missing, boundaries, assessments = spec
        packet = packets[qid]
        entries = []
        for hit, manual in zip(packet["evidence"], assessments):
            fid, relation, helpful, quote, explanation, warnings = manual
            if hit["file_id"] != fid:
                raise ValueError("Manual reading position differs from actual evidence")
            entries.append({"file_id": fid, "unit_id": hit["unit_id"], "rank": hit["rank"], "relation": relation,
                            "helpful": helpful, "quote": quote, "reason": explanation, "warnings": warnings})
        judgments.append({"query_id": qid, "input_sha256": packet["input_sha256"], "packet_sha256": demo.sha_json(packet),
            "origin": "current_session_model", "human_approved": False, "decision": decision, "reason": reason,
            "risk_labels": [{"risk_tag": tag, "certainty": certainty, "input_quote": quote, "evidence_file_ids": files,
                             "limitations": limitation} for tag, certainty, quote, files, limitation in risk_labels],
            "missing_information": missing, "boundary_notes": boundaries, "evidence_assessments": entries})
    demo.write_new(demo.OUT / "model_judgments.jsonl", judgments, True)
    demo.write_new(demo.OUT / "reading_record.json", {"reader": "current_session_model", "queries_read": list(SPECS),
        "evidence_positions_read": 80, "read_batch_order": [["D001","D002","D003","D004"],["D005","D006","D007","D008"],
        ["D009","D010","D011","D012"],["D013","D014","D015","D016"]],
        "input_author_is_same_session_judge": True, "method_blind": False, "human_approved": False,
        "semantic_decisions": "All SPEC relations, helpfulness, quotes, reasons and labels were explicitly authored after reading actual displayed texts; code only binds and serializes.",
        "packets_sha256": demo.sha_file(demo.OUT / "evidence_packets.jsonl")})


if __name__ == "__main__":
    main()
